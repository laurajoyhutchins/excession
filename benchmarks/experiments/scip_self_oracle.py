#!/usr/bin/env python3
"""Replay *actual* rust-analyzer SCIP output through Excession's concepts CLI.

The index is generated by rust-analyzer in the workflow, then independently
decoded by the official scip CLI. This script does not execute an indexer.
The oracle verifies source-bound interpretation, not indexer truth.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import subprocess
import sys
import tempfile

from concepts_scip_oracle import reconcile, native_references


def run(*args: object) -> bytes:
    proc = subprocess.run([str(x) for x in args], capture_output=True,
                          check=False, timeout=180)
    if proc.returncode != 0:
        raise RuntimeError(
            f"command {args[0]} failed ({proc.returncode}): "
            f"{proc.stderr.decode(errors='replace')[:2000]}"
        )
    return proc.stdout


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bin", required=True, type=Path)
    parser.add_argument("--repo", required=True, type=Path)
    parser.add_argument("--index", required=True, type=Path,
                        help="official scip print --json output of rust-analyzer scip")
    parser.add_argument("--source-prefix", default="core")
    parser.add_argument("--out", required=True, type=Path)
    parser.add_argument("--indexer-diagnostics", type=Path)
    args = parser.parse_args()

    repo = args.repo.resolve()
    commit = run("git", "-C", repo, "rev-parse", "HEAD").decode().strip()
    tree = run("git", "-C", repo, "rev-parse", "HEAD^{tree}").decode().strip()
    native = json.loads(args.index.read_bytes())
    if not isinstance(native, dict) or not isinstance(native.get("documents"), list):
        raise ValueError("official SCIP output is not a decoded index")
    expected, _, _ = native_references(native, args.source_prefix)
    if not expected:
        raise ValueError("rust-analyzer SCIP did not expose any unique cross-file references")

    common = [
        "--repo", repo, "--rev", commit, "--index", args.index,
        "--source-prefix", args.source_prefix,
    ]
    def command(verb: str, *other: object) -> dict:
        return json.loads(run(args.bin, "concepts", verb, *common, *other))

    # Keep the native index unmodified for both Rust and the Python oracle.
    with tempfile.TemporaryDirectory(prefix="excession-rust-scip-oracle-") as folder:
        db = Path(folder) / "source-snapshot.sqlite"
        batch = command("scip-normalize")
        model = command("scip-preview")
        manifest = command("scip-compile", "--db", db)
        audit = command("scip-audit", "--db", db, "--snapshot", manifest["snapshot_id"])
        if command("scip-compile", "--db", db) != manifest:
            raise ValueError("non-deterministic rust-analyzer SCIP projection")
        oracle = reconcile(
            native, batch, model, manifest, audit, repo, commit, tree,
            source_prefix=args.source_prefix,
        )

    diagnostics = args.indexer_diagnostics.read_text(errors="replace") if args.indexer_diagnostics else ""
    report = {
        "schema": "excession.concepts-rust-native-evidence.v1",
        "indexer_duplicate_symbol_warning": "Duplicate symbols encountered" in diagnostics,
        "indexer": "rust-analyzer scip",
        "decoder": "scip print --json",
        "source_commit": commit,
        "source_tree": tree,
        "source_prefix": args.source_prefix,
        "verified_native_references": len(expected),
        "concepts": oracle,
        "completeness": "PARTIAL_INDEX_SCOPE_ONLY",
        "verified_native_indexer_semantic_correctness": False,
        "indexer_reexecuted_by_this_script": False,
    }
    args.out.mkdir(parents=True, exist_ok=True)
    artifacts = {
        "batch": batch,
        "model": model,
        "snapshot": manifest,
        "audit": audit,
        "oracle": oracle,
        "summary": report,
    }
    for name, data in artifacts.items():
        (args.out / f"{name}.json").write_text(
            json.dumps(data, indent=2, sort_keys=True) + "\n", encoding="utf-8"
        )
    print(json.dumps(report, indent=2, sort_keys=True))


if __name__ == "__main__":
    main()
