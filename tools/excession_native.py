#!/usr/bin/env python3
"""Offline, compiler-assisted input discovery for pinned Git commits.

These are declared *source* dependencies, not behavioral guarantees. Native
compiler tools may parse adversarial source: their invocation requires explicit
--trusted-local. The resolver never deliberately executes project source.
"""
import argparse
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
import tomllib
from pathlib import Path, PurePosixPath
from excession_discover import Tree, Unsupported

MAX_STAGE_FILES = 4096
MAX_STAGE_BYTES = 96 * 1024 * 1024
MAX_INPUT_FILES = 512
MAX_INPUT_BYTES = 32 * 1024 * 1024


def call(argv, cwd=None, env=None, timeout=45):
    try:
        p = subprocess.run(argv, cwd=cwd, env=env, stdout=subprocess.PIPE,
                           stderr=subprocess.PIPE, timeout=timeout)
    except (OSError, subprocess.TimeoutExpired) as e:
        raise Unsupported(f'native resolver unavailable/timed out: {e}') from e
    if p.returncode or len(p.stdout) > 16 * 1024 * 1024:
        raise Unsupported('native resolver failed: ' + p.stderr[:700].decode(errors='replace'))
    return p.stdout


def executable(name):
    found = shutil.which(name)
    if found is None:
        raise Unsupported(f'native adapter requires installed {name}')
    return Path(found).resolve()


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def safe(path):
    if not path or '\\' in path or '\x00' in path or path.startswith('/') or any(
            x in ('', '.', '..') for x in path.split('/')) or path == '.git' or path.startswith('.git/'):
        raise Unsupported(f'unsafe Git pathname: {path!r}')


def stage(tree, root):
    size = count = 0
    for path, (mode, kind) in sorted(tree.modes.items()):
        safe(path)
        if (mode, kind) not in (('100644', 'blob'), ('100755', 'blob')):
            continue   # unresolved symlink references fail on native resolution
        count += 1
        if count > MAX_STAGE_FILES:
            raise Unsupported('historical snapshot exceeds staging file limit')
        content = call(['git', '-C', str(tree.repo), 'show', f'{tree.commit}:{path}'], timeout=20)
        size += len(content)
        if size > MAX_STAGE_BYTES:
            raise Unsupported('historical snapshot exceeds 96 MiB staging limit')
        target = root / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(content)
        target.chmod(0o444)
    return count, size


def rel(root, resolved):
    try:
        value = Path(resolved).resolve(strict=True).relative_to(root.resolve()).as_posix()
    except (OSError, ValueError) as e:
        raise Unsupported(f'native dependency outside pinned Git snapshot: {resolved}') from e
    safe(value)
    return value


def go_resolve(root, entry, go):
    if not (root / 'go.mod').is_file() or (root / 'go.work').exists():
        raise Unsupported('Go requires one tracked go.mod and no go.work')
    dirname = PurePosixPath(entry).parent.as_posix()
    env = {'PATH': os.environ.get('PATH', '/usr/local/go/bin:/usr/bin:/bin'),
           'HOME': str(root), 'GOCACHE': str(root.parent / 'go-cache'),
           'GOMODCACHE': str(root.parent / 'go-mod-cache'),
           'GOPROXY': 'off', 'GOSUMDB': 'off', 'GOTOOLCHAIN': 'local',
           'GOWORK': 'off', 'CGO_ENABLED': '0', 'GOFLAGS': '-mod=readonly',
           'LC_ALL': 'C', 'TZ': 'UTC'}
    output = call([str(go), 'list', '-deps', '-test', '-json',
                   './' if dirname == '.' else './' + dirname], cwd=root, env=env)
    decoder = json.JSONDecoder()
    text = output.decode()
    offset = 0
    selected, package_dirs = set(), set()
    while offset < len(text):
        while offset < len(text) and text[offset].isspace():
            offset += 1
        if offset == len(text):
            break
        item, offset = decoder.raw_decode(text, offset)
        if item.get('Error') or item.get('DepsErrors'):
            raise Unsupported('Go native resolver reported dependency errors')
        if item.get('Standard'):
            continue
        directory = item.get('Dir')
        if not directory:
            raise Unsupported('native Go package has no directory')
        # go list -test emits a synthetic testmain package in GOCACHE.
        # Its generated bytes are Go-toolchain outputs, not Git source.
        if str(item.get('ImportPath', '')).endswith('.test'):
            continue
        package_dirs.add(rel(root, directory)) if Path(directory) != root else package_dirs.add('.')
        if any(item.get(k) for k in ('CgoFiles', 'SwigFiles', 'SwigCXXFiles')):
            raise Unsupported('Go cgo/SWIG requires a separate toolchain effects contract')
        for key in ('GoFiles', 'TestGoFiles', 'XTestGoFiles', 'SFiles',
                    'CFiles', 'CXXFiles', 'HFiles', 'EmbedFiles',
                    'TestEmbedFiles', 'XTestEmbedFiles', 'SysoFiles'):
            for filename in item.get(key, []):
                selected.add(rel(root, Path(directory) / filename))
    # Over-approximate build-tag alternatives in every reached package dir.
    for file in root.rglob('*.go'):
        if file.is_file() and file.relative_to(root).parent.as_posix() in package_dirs:
            selected.add(file.relative_to(root).as_posix())
    if entry not in selected:
        raise Unsupported('entry not reached by go list')
    config = {p for p in ('go.mod', 'go.sum') if (root / p).is_file()}
    return selected, config, {'go-flags': 'CGO_ENABLED=0,GOWORK=off,GOPROXY=off'}


def js_resolve(root, entry, node, tsc):
    ts_api = tsc.parent.parent / 'lib' / 'typescript.js'
    if not ts_api.is_file():
        raise Unsupported('TypeScript compiler API not found beside tsc')
    helper = Path(__file__).with_name('excession_ts_resolve.cjs')
    env = {'PATH': os.environ.get('PATH', '/usr/bin:/bin'), 'HOME': str(root),
           'NODE_OPTIONS': '', 'NODE_PATH': '', 'LC_ALL': 'C', 'TZ': 'UTC'}
    outcome = json.loads(call([str(node), str(helper), str(ts_api), str(root), entry],
                              cwd=root, env=env))
    return set(outcome['sources']), set(outcome['configuration']), {
        'typescript-api-sha256': sha(ts_api),
        'typescript-options': outcome['options_sha256']}


def rust_resolve(root, entry, rustc):
    config_file = root / 'Cargo.toml'
    if not config_file.is_file():
        raise Unsupported('Rust requires tracked Cargo.toml')
    manifest = tomllib.loads(config_file.read_text())
    if 'workspace' in manifest or any(manifest.get(k) for k in
           ('dependencies', 'dev-dependencies', 'build-dependencies', 'patch', 'replace')):
        raise Unsupported('Rust workspace/external dependencies not supported by rustc-only adapter')
    package = manifest.get('package', {})
    if not isinstance(package, dict) or package.get('build') is not None or (root/'build.rs').exists():
        raise Unsupported('Rust build script cannot be isolated in this resolver')
    if (root/'.cargo/config.toml').exists():
        raise Unsupported('Rust cargo configuration requires native Cargo interpretation')
    edition = package.get('edition', '2015')
    if edition not in ('2015','2018','2021','2024') or entry not in ('src/lib.rs', 'src/main.rs'):
        raise Unsupported('unsupported Rust crate root or edition')
    for path in root.rglob('*.rs'):
        if re.search(r'\b(?:env|option_env|concat|include)!\s*\(', path.read_text(errors='replace')):
            raise Unsupported('Rust compile-time environment or dynamic include not bounded')
    depfile = root.parent / 'rust-dependencies.d'
    env = {'PATH': os.environ.get('PATH','/usr/bin:/bin'), 'HOME': str(root),
           'LC_ALL': 'C', 'TZ': 'UTC', 'CARGO_MANIFEST_DIR': str(root),
           'CARGO_PKG_NAME': str(package.get('name', 'probe'))}
    call([str(rustc), '--crate-name', 'excession_native_probe', '--crate-type',
          'lib' if entry == 'src/lib.rs' else 'bin', '--edition', edition,
          '--emit', f'dep-info={depfile}', str(root/entry)], cwd=root, env=env)
    data = depfile.read_text()
    first = data.splitlines()[0]
    if ': ' not in first or any(escape in first for escape in ('\\ ', '\\#', '\\:')):
        raise Unsupported('rustc emitted unsupported dep-info syntax')
    selected = {rel(root, path) for path in first.split(': ', 1)[1].split()}
    if entry not in selected:
        raise Unsupported('rustc dep-info omitted entrypoint')
    config = {p for p in ('Cargo.toml','Cargo.lock','rust-toolchain','rust-toolchain.toml')
              if (root / p).is_file()}
    return selected, config, {'rustc-edition': edition, 'rustc-mode': 'dep-info-no-externs'}


def discover(repo, revision, entry, language):
    safe(entry)
    tree = Tree(repo, revision)
    if not tree.exists(entry):
        raise Unsupported('entrypoint absent from tracked revision')
    start = time.monotonic_ns()
    with tempfile.TemporaryDirectory(prefix='excession-native-') as temp:
        root = Path(temp) / 'src'
        root.mkdir()
        staged_files, staged_bytes = stage(tree, root)
        if language == 'go':
            exe = executable('go')
            selected, config, assumptions = go_resolve(root, entry, exe)
            version = call([str(exe), 'version']).decode().strip()
        elif language in ('javascript','typescript'):
            exe = executable('node')
            selected, config, assumptions = js_resolve(root, entry, exe, executable('tsc'))
            version = call([str(exe), '--version']).decode().strip()
        elif language == 'rust':
            exe = executable('rustc')
            selected, config, assumptions = rust_resolve(root, entry, exe)
            version = call([str(exe), '--version']).decode().strip()
        else:
            raise Unsupported('unknown native language adapter')
        inputs = {p: 'source' for p in selected}
        for p in config:
            inputs[p] = 'configuration'
        if entry not in inputs or len(inputs) > MAX_INPUT_FILES:
            raise Unsupported('entry missing or input count exceeds 512')
        total = 0
        for name in inputs:
            safe(name)
            if not tree.exists(name):
                raise Unsupported(f'untracked native dependency: {name}')
            total += (root / name).stat().st_size
        if total > MAX_INPUT_BYTES:
            raise Unsupported('input bytes exceed 32 MiB')
        assumptions.update({'dependency-discovery': 'excession-toolchain-native-v1',
                            'toolchain-version': version[:180],
                            'toolchain-sha256': sha(exe),
                            'platform': f'{sys.platform}-{os.uname().machine}'})
        declaration = {'schema': 'excession.input-declaration.v1',
                       'coverage': 'DECLARED_INPUTS_ONLY', 'language': language,
                       'subject': entry,
                       'inputs': [{'path':p,'role':r} for p,r in sorted(inputs.items())],
                       'assumptions': assumptions}
        stats = {'commit': tree.commit, 'staged_files': staged_files,
                 'staged_bytes': staged_bytes, 'declared_files': len(inputs),
                 'declared_bytes': total, 'elapsed_ns': time.monotonic_ns() - start}
        return declaration, stats


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('repo', type=Path)
    p.add_argument('entry')
    p.add_argument('--revision', default='HEAD')
    p.add_argument('--language', choices=['go','javascript','typescript','rust'], required=True)
    p.add_argument('--trusted-local', action='store_true')
    p.add_argument('--stats', type=Path)
    args = p.parse_args()
    try:
        if not args.trusted_local:
            raise Unsupported('native compiler use requires explicit --trusted-local')
        result, stats = discover(args.repo, args.revision, args.entry, args.language)
        if args.stats:
            args.stats.write_text(json.dumps(stats, sort_keys=True)+'\n')
        print(json.dumps(result, sort_keys=True, separators=(',', ':')))
    except (Unsupported, ValueError, UnicodeError, OSError, json.JSONDecodeError) as error:
        print('UNSUPPORTED: '+str(error), file=sys.stderr)
        sys.exit(2)

if __name__ == '__main__':
    main()
